// Copies the IDL and types that `anchor build` generates into src/idl so the package
// has no dependency on the Rust build output. Run after changing the program.
import { copyFileSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../../../target');
const out = resolve(here, '../src/idl');
mkdirSync(out, { recursive: true });

const idl = readFileSync(resolve(target, 'idl/orbital.json'), 'utf8');
writeFileSync(resolve(out, 'orbital.ts'), `// Generated by scripts/sync-idl.mjs from target/idl/orbital.json. Do not edit.\nexport const IDL = ${idl.trim()} as const;\n`);
copyFileSync(resolve(target, 'types/orbital.ts'), resolve(out, 'orbital-types.ts'));
console.log('synced IDL');
